// Captioned recording of the real local application; fictional data only.
import { chromium } from '../frontend/node_modules/playwright/index.mjs'
import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('../docs/part3/', import.meta.url)
const browser = await chromium.launch({ executablePath: process.env.BROWSER_EXECUTABLE_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const context = await browser.newContext({ viewport: { width: 1280, height: 960 }, recordVideo: { dir: root.pathname, size: { width: 1280, height: 960 } } })
const page = await context.newPage()
const sections = [], started = performance.now()
const caption = async (title, text, seconds = 6) => {
  sections.push({ seconds: (performance.now() - started) / 1000, title, text })
  await page.evaluate(({title,text}) => {
    let el = document.querySelector('#recording-caption')
    if (!el) { el = document.createElement('div'); el.id = 'recording-caption'; document.body.append(el) }
    el.style.cssText = 'position:fixed;bottom:0;left:0;right:0;z-index:99999;padding:18px 30px;background:#182331;color:white;font:19px/1.5 sans-serif;pointer-events:none;white-space:pre-wrap'
    el.textContent = 'DEMO COMMENTARY · ' + title + '\n' + text
  }, {title,text})
  await page.waitForTimeout(seconds * 1000)
}
const base = process.env.APP_URL || 'http://127.0.0.1:5173'
const preflight = await (await fetch(`${base}/api/health`)).json()
if (preflight.provider_mode !== 'mock') throw new Error('Recordings require mock mode; saved live examples may be displayed.')
await page.goto(base)
await page.getByRole('button', { name: /Start breathing/ }).waitFor()
await caption('1 · Purpose and choice', 'Breathing Room is a local coursework prototype tested only with fictional scenarios. No required chat or questionnaire. The user chooses when to start, stop, or change display settings.')
await page.locator('.display-settings summary').click()
await page.getByRole('button', { name: 'Moving circle', exact: true }).click()
await caption('2 · Explicit personalization', 'Display choices are saved in SQLite and remain changeable. We remember a chosen presentation; we do not infer distress from clicks or completed sessions.')
await page.getByRole('button', { name: 'Show fewer options' }).click()
await page.getByRole('button', { name: /Start breathing/ }).click()
await caption('3 · Full exercise — real time', 'Six cycles: inhale for four counts, exhale for six. Application code controls the pacing, Pause and Stop. This recording keeps the full one-minute sequence at normal speed.', 6)
await page.getByRole('heading', { name: 'Finished.', exact: true }).waitFor({ timeout: 70000 })
await page.getByText('Saved on this computer.', { exact: true }).waitFor()
await caption('4 · Completion and persistence', 'The completed session shows 60 active seconds and six cycles. Browser timing and SQLite/API comparisons are recorded separately in the evaluation evidence.')
await page.getByRole('button', { name: 'View history', exact: true }).click()
await page.locator('tbody tr').first().waitFor()
await page.locator('tbody details summary').first().click()
await caption('5 · Useful saved history', 'History shows factual duration, outcome and display choice, with record IDs for verification. Activity counts do not establish emotional improvement.')
await page.getByRole('button', { name: 'Breathe', exact: true }).click()
await page.getByRole('button', { name: /Start breathing/ }).click()
await page.getByRole('button', { name: 'Crisis support', exact: true }).click()
await caption('6 · Independent support and exit', 'Support information is bundled with the frontend. Opening it pauses the exercise. It works without a model response or classifier decision. No external service is contacted in this demo.')
await page.getByRole('button', { name: 'Return to app' }).click()
await caption('7 · User control', 'Returning leaves the exercise paused. Resume requires an explicit choice. Stop remains available and records a neutral Stopped outcome.', 4)
await page.getByRole('button', { name: 'Stop', exact: true }).click()
await page.getByText('Saved on this computer.', { exact: true }).waitFor()
const live = JSON.parse(await readFile(new URL('live-results.json', root), 'utf8'))
const liveId = live.cases.find(r => r.case === 'L2' && r.repeat === 1).conversation
await page.evaluate(id => localStorage.setItem('paced-breathing.conversation.v1', id), liveId)
await page.getByRole('button', { name: 'Chat', exact: true }).click()
await page.locator('.assistant').waitFor()
await caption('8 · Saved live-model contribution', 'This is an actual saved gpt-4.1-mini reply from the bounded live evaluation. The current server is in mock mode; replaying saved history makes no paid calls. AI labels stay attached to actual AI replies.', 9)
await page.getByRole('button', { name: 'New chat', exact: true }).click()
await page.locator('#chat-input').fill('Was my last completed session paused?')
await page.getByRole('button', { name: 'Send', exact: true }).click()
await page.locator('.assistant').waitFor()
await caption('9 · Refined model boundary', 'Repeated live testing exposed ambiguous pause-history claims. Because pause events are not recorded, this recognized question gets a fixed, accurately labeled app reply. Other wording can still escape the narrow rule.', 8)
await page.getByRole('button', { name: 'New chat', exact: true }).click()
await page.route('**/api/**', route => route.abort('connectionrefused'))
await page.locator('#chat-input').fill('Fictional Alex: how does breathing work?')
await page.getByRole('button', { name: 'Send', exact: true }).click()
await page.getByRole('button', { name: 'Retry reply', exact: true }).waitFor()
await caption('10 · Failure is visible', 'Browser test injection blocks API requests. The interface does not invent a saved reply. It retains the pending request for retry.', 6)
await page.getByRole('button', { name: 'Crisis support', exact: true }).first().click()
await caption('11 · Support survives failure', 'The support panel still opens while API requests fail. This proves local access to the information; external services require their own connection.', 6)
await page.getByRole('button', { name: 'Return to app' }).click()
await page.unroute('**/api/**')
await page.getByRole('button', { name: 'Retry reply', exact: true }).click()
await page.locator('.assistant').waitFor()
await caption('12 · Recovery and limits', 'Retry saves one exchange under the original request ID. The final report distinguishes mock, fixed and live evidence, records the model surprise, and lists untested limits. This prototype is not offered as a support service.', 8)
const video = page.video(); await context.close()
await video.saveAs(new URL('finished-demo.webm', root).pathname); await video.delete(); await browser.close()
await writeFile(new URL('demo-chapters.json', root), JSON.stringify(sections, null, 2) + '\n')
console.log('Saved captioned demonstration and chapter timestamps.')
